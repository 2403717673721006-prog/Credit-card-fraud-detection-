import os
import sys
import json
from pathlib import Path
import pandas as pd
import numpy as np
import joblib

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import seaborn as sns

# Add project root to sys.path
SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from backend.config import (
    DATASET_PATH,
    ML_DIR,
    ARTIFACTS_DIR as BACKEND_ARTIFACTS_DIR,
)

ML_ARTIFACTS_DIR = ML_DIR / "artifacts"


def generate_evaluation_visualizations():
    """
    Reads the model_comparison.json generated by train.py and creates
    professional dark-themed evaluation figures.
    """
    comp_path = BACKEND_ARTIFACTS_DIR / "model_comparison.json"
    if not comp_path.exists():
        print(f"[Evaluate] No model_comparison.json found at {comp_path}. Run ml/train.py first.")
        return

    with open(comp_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    models_data = data["models"]

    plt.style.use("dark_background")
    plt.rcParams["font.sans-serif"] = "DejaVu Sans"
    plt.rcParams["axes.edgecolor"] = "#334155"

    # 1. Bar Chart: Model Metrics Comparison
    names = list(models_data.keys())
    precisions = [models_data[m]["precision"] for m in names]
    recalls = [models_data[m]["recall"] for m in names]
    f1_scores = [models_data[m]["f1_score"] for m in names]
    avg_precs = [models_data[m]["average_precision"] for m in names]

    x = np.arange(len(names))
    width = 0.18

    fig, ax = plt.subplots(figsize=(10, 5), dpi=150)
    ax.bar(x - 1.5 * width, precisions, width, label="Precision", color="#38bdf8")
    ax.bar(x - 0.5 * width, recalls, width, label="Recall", color="#34d399")
    ax.bar(x + 0.5 * width, f1_scores, width, label="F1-Score", color="#f59e0b")
    ax.bar(x + 1.5 * width, avg_precs, width, label="Avg Precision (PR-AUC)", color="#a855f7")

    ax.set_ylabel("Metric Score (0.0 to 1.0)", fontsize=10, color="#94a3b8")
    ax.set_title("Machine Learning Models Evaluation Benchmark (Fraud Detection)", fontsize=13, fontweight="bold", pad=14, color="#e2e8f0")
    ax.set_xticks(x)
    ax.set_xticklabels(names, fontsize=10, color="#cbd5e1")
    ax.set_ylim(0, 1.1)
    ax.legend(frameon=True, facecolor="#0f172a", edgecolor="#334155", loc="upper left")
    ax.grid(axis="y", linestyle="--", alpha=0.25)
    plt.tight_layout()
    plt.savefig(ML_ARTIFACTS_DIR / "model_metrics_comparison.png")
    plt.savefig(BACKEND_ARTIFACTS_DIR / "model_metrics_comparison.png")
    plt.close()

    # 2. Confusion Matrices Subplots (2x2)
    fig, axes = plt.subplots(2, 2, figsize=(9, 7), dpi=150)
    axes = axes.flatten()

    for idx, name in enumerate(names):
        cm = np.array(models_data[name]["confusion_matrix"])
        ax = axes[idx]
        sns.heatmap(
            cm,
            annot=True,
            fmt="d",
            cmap="Blues",
            cbar=False,
            ax=ax,
            annot_kws={"size": 11, "fontweight": "bold"},
            xticklabels=["Pred Legit", "Pred Fraud"],
            yticklabels=["Actual Legit", "Actual Fraud"],
        )
        ax.set_title(f"{name}\n(F1: {models_data[name]['f1_score']:.3f} | PR-AUC: {models_data[name]['average_precision']:.3f})", fontsize=10, color="#e2e8f0", pad=8)

    plt.suptitle("Confusion Matrix Breakdown across 56,962 Test Transactions", fontsize=13, fontweight="bold", color="#f1f5f9", y=1.02)
    plt.tight_layout()
    plt.savefig(ML_ARTIFACTS_DIR / "confusion_matrices_comparison.png")
    plt.savefig(BACKEND_ARTIFACTS_DIR / "confusion_matrices_comparison.png")
    plt.close()

    print(f"[Evaluate] Generated evaluation charts in {ML_ARTIFACTS_DIR} and {BACKEND_ARTIFACTS_DIR}")


if __name__ == "__main__":
    generate_evaluation_visualizations()
